#!/usr/bin/env bash
# Interactive setup for local play: asks a few questions, writes .env.local,
# pre-pulls the Docker images (app + Cloudflare tunnel), then offers to launch.
# Re-run any time to change your settings. Linux / macOS.
set -euo pipefail
cd "$(dirname "$0")"

COMPOSE="docker compose -f docker-compose.local.yml"
ENV_FILE=".env.local"

say()  { printf '%s\n' "$*"; }
# ask "Prompt" "default" -> sets REPLY_VAL (falls back to default on empty input / EOF)
ask()  { local p="$1" d="${2:-}" v=""; if [ -n "$d" ]; then read -r -p "$p [$d]: " v || true; else read -r -p "$p: " v || true; fi; REPLY_VAL="${v:-$d}"; }
# yesno "Prompt" Y|N -> exit 0 for yes. End of input (no terminal) counts as "no".
yesno() { local p="$1" d="${2:-Y}" v=""; read -r -p "$p [$([ "$d" = Y ] && echo Y/n || echo y/N)]: " v || return 1; v="${v:-$d}"; case "$v" in [Yy]*) return 0;; *) return 1;; esac; }
rand_hex() { od -An -N"$1" -tx1 /dev/urandom | tr -d ' \n'; }
valid() { case "$1" in ''|*[!A-Za-z0-9_-]*) return 1;; *) return 0;; esac; }

say "KoPlay setup"
say "============"
say

# --- Docker --------------------------------------------------------------
if ! command -v docker >/dev/null 2>&1; then
  say "Docker is required but was not found."
  case "$(uname -s)" in
    Darwin) say "Install Docker Desktop: https://docs.docker.com/desktop/setup/install/mac-install/" ;;
    *)      say "Install Docker Engine: https://docs.docker.com/engine/install/  (then re-run ./setup.sh)" ;;
  esac
  exit 1
fi
if ! docker info >/dev/null 2>&1; then
  say "Docker is installed but not running (or your user can't access it). Start Docker and re-run."
  exit 1
fi
if ! docker compose version >/dev/null 2>&1; then
  say "The 'docker compose' plugin is required: https://docs.docker.com/compose/install/"
  exit 1
fi
say "Docker: OK"

# --- Existing config -----------------------------------------------------
if [ -f "$ENV_FILE" ]; then
  say
  if yesno "$ENV_FILE already exists. Reconfigure it?" N; then :; else
    say "Keeping existing settings."
    SKIP_CONFIG=1
  fi
fi

# --- Questions -----------------------------------------------------------
if [ -z "${SKIP_CONFIG:-}" ]; then
  say
  say "A few questions (press Enter to accept the default)."
  say

  while :; do
    ask "Your name (shown as the host; letters, numbers, - and _)" "Host"
    HOST_NAME="$REPLY_VAL"; valid "$HOST_NAME" && break; say "  Use only letters, numbers, - and _."
  done

  DEFAULT_CODE="$(rand_hex 3 | tr 'a-f' 'A-F')"
  say
  say "The host access code is typed on the first phone to join; that player becomes host."
  while :; do
    ask "Host access code (letters/numbers)" "$DEFAULT_CODE"
    CODE="$REPLY_VAL"; valid "$CODE" && break; say "  Use only letters, numbers, - and _."
  done

  say
  say "AI quiz generation is optional. Without a Gemini API key you can still play saved"
  say "quizzes and upload your own as JSON (see docs/access-and-quizzes.md)."
  GEMINI_KEY=""
  if yesno "Enable AI quiz generation with a Gemini API key?" N; then
    say "  Get a key at https://aistudio.google.com/apikey"
    read -rs -p "  Paste your Gemini API key (input hidden, Enter to skip): " GEMINI_KEY || true
    say
  fi

  say
  while :; do
    ask "Local port" "${LOCAL_PORT:-3000}"
    PORT_LOCAL="$REPLY_VAL"
    case "$PORT_LOCAL" in ''|*[!0-9]*) say "  Enter a number." ;; *) [ "$PORT_LOCAL" -ge 1 ] && [ "$PORT_LOCAL" -le 65535 ] && break; say "  Enter a port from 1 to 65535." ;; esac
  done

  SCREEN="$(rand_hex 16)"
  umask 077
  cat > "$ENV_FILE" <<ENV
# Generated by setup.sh - safe to edit, or re-run ./setup.sh. Not committed to git.
# Host access code: type this on the first phone to join (that player becomes host).
USERS='{"$CODE":{"name":"$HOST_NAME","role":15}}'
SCREENS='{"$SCREEN":{"label":"Local screen","owners":["$HOST_NAME"]}}'
LOCAL_PORT=$PORT_LOCAL
# Optional: enables AI quiz generation.
GEMINI_API_KEY=$GEMINI_KEY
ENV
  say
  say "Wrote $ENV_FILE"
fi

# --- Pre-pull images -----------------------------------------------------
say
say "Preparing Docker images (the Cloudflare tunnel needs no separate install; it runs as a container)..."
$COMPOSE pull tunnel
$COMPOSE build app
say "Images ready."

# --- Launch --------------------------------------------------------------
say
if yesno "Launch the screen now?" Y; then
  exec ./start.sh
fi
say
say "All set. Start any time with:  ./start.sh"
