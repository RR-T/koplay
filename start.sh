#!/usr/bin/env bash
# One-command local play: starts KoPlay + a public tunnel, opens the display.
# Requires Docker. Stop with Ctrl+C.
set -euo pipefail
cd "$(dirname "$0")"

COMPOSE="docker compose -f docker-compose.local.yml"
PORT_LOCAL="${LOCAL_PORT:-3000}"

command -v docker >/dev/null || { echo "Docker is required: https://docs.docker.com/get-docker/"; exit 1; }
docker info >/dev/null 2>&1 || { echo "Docker is installed but not running. Start Docker and try again."; exit 1; }

rand_hex() { od -An -N"$1" -tx1 /dev/urandom | tr -d ' \n'; }

# First run: generate a private host code and screen ID.
if [ ! -f .env.local ]; then
  CODE="$(rand_hex 3 | tr 'a-f' 'A-F')"
  SCREEN="$(rand_hex 16)"
  GEMINI=""
  if [ -f .env ]; then GEMINI="$(grep -E '^GEMINI_API_KEY=' .env || true)"; fi
  cat > .env.local <<ENV
# Generated by start.sh — safe to edit. Not committed to git.
# Host access code: type this on the first phone to join (that player becomes host).
USERS='{"$CODE":{"name":"Host","role":15}}'
SCREENS='{"$SCREEN":{"label":"Local screen","owners":["Host"]}}'
# Add a key to enable Trivia quiz generation:
${GEMINI:-GEMINI_API_KEY=}
ENV
  echo "Created .env.local"
fi

CODE="$(sed -n "s/^USERS='{\"\([^\"]*\)\".*/\1/p" .env.local)"
SCREEN="$(sed -n "s/^SCREENS='{\"\([^\"]*\)\".*/\1/p" .env.local)"
[ -n "$CODE" ] && [ -n "$SCREEN" ] || { echo "Could not read USERS/SCREENS from .env.local. Delete it to regenerate."; exit 1; }

cleanup() { echo; echo "Stopping..."; $COMPOSE down >/dev/null 2>&1 || true; }
trap cleanup EXIT
trap 'exit 0' INT TERM

echo "Starting KoPlay (first run builds the image, this can take a few minutes)..."
$COMPOSE up --build -d

echo "Waiting for the public tunnel URL..."
URL=""
for _ in $(seq 1 60); do
  URL="$($COMPOSE logs tunnel 2>&1 | grep -oE 'https://[a-z0-9-]+\.trycloudflare\.com' | head -1 || true)"
  [ -n "$URL" ] && break
  sleep 1
done
[ -n "$URL" ] || { echo "Tunnel did not start. Logs:"; $COMPOSE logs tunnel | tail -20; exit 1; }

echo "Waiting for the app..."
for _ in $(seq 1 30); do
  curl -fs -o /dev/null "http://localhost:$PORT_LOCAL/" && break
  sleep 1
done

DISPLAY_URL="$URL/screen/$SCREEN"
echo
echo "  Display (open on the big screen):  $DISPLAY_URL"
echo "  Phones join at:                    $URL"
echo "  Host access code:                  $CODE   (first player to join types this)"
echo
echo "Press Ctrl+C to stop."

if command -v open >/dev/null; then open "$DISPLAY_URL"
elif command -v xdg-open >/dev/null; then xdg-open "$DISPLAY_URL" >/dev/null 2>&1 || true
fi

$COMPOSE logs -f app
